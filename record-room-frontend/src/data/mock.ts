const DAY = 86_400_000;

/** Fixed "now" so seeded timestamps stay stable across reloads. */
export const SEED_NOW = '2026-10-03T09:30:00.000Z';

const iso = (offsetDays: number, hours = 9, minutes = 15) => {
  const base = new Date(SEED_NOW).getTime() - offsetDays * DAY;
  const d = new Date(base);
  d.setUTCHours(hours, minutes, 0, 0);
  return d.toISOString();
};

const day = (offsetDays: number) => iso(offsetDays).slice(0, 10);

