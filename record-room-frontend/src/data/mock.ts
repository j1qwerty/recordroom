/** Flattened lookup used by the seed generator and by tests. */
export const shelfIndex = new Map<string, { shelf: Shelf; unit: StorageUnit; section: Section }>();
rooms.forEach((room) => {
  room.sections.forEach((section) => {
    room.storageUnits
      .filter((unit) => unit.sectionId === section.id)
      .forEach((unit) => {
        unit.shelves.forEach((shelf) => shelfIndex.set(shelf.id, { shelf, unit, section }));
      });
  });
});

const shelfAt = (shelfId: string) => shelfIndex.get(shelfId);

