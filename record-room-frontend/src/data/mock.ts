const shelfStatuses: StorageStatus[] = ['Active', 'Active', 'Active', 'Maintenance'];

function buildShelves(almirahId: string, prefix: string, capacity: number): Shelf[] {
  return Array.from({ length: 4 }, (_, index) => ({
    id: `${almirahId}-s${index + 1}`,
    almirahId,
    barcode: `${prefix}SH${String(index + 1).padStart(2, '0')}`,
    code: `${prefix}-S-${String(index + 1).padStart(2, '0')}`,
    name: `Shelf ${index + 1}`,
    status: shelfStatuses[index],
    capacity,
    occupied: Math.round(capacity * (0.32 + ((index * 13) % 40) / 100)),
    position: index,
  }));
}

function buildAlmirahs(roomId: string, sectionId: string, prefix: string, startIndex: number) {
  return Array.from({ length: 2 }, (_, i): StorageUnit => {
    const code = `A-${String(startIndex + i * 2).padStart(3, '0')}`;
    const id = `unit-${code.toLowerCase()}`;
    return {
      id,
      sectionId,
      roomId,
      barcode: `${prefix}${String(startIndex + i * 2).padStart(3, '0')}`,
      code,
      name: `Almirah ${String(startIndex + i * 2).padStart(3, '0')}`,
      type: 'Almirah',
      status: code === 'A-010' ? 'Maintenance' : 'Active',
      x: i === 0 ? 8 : 54,
      y: 10,
      width: i === 0 ? 18 : 22,
      height: 76,
      shelves: buildShelves(id, `LKO${roomId.replace('room-', '')}`, 80),
    };
  });
}

function buildSections(roomId: string, names: string[]): Section[] {
  return names.map((name, index) => ({
    id: `${roomId}-sec-${String.fromCharCode(97 + index)}`,
    roomId,
    code: `SEC-${name}`,
    name,
    status: name === 'C' ? 'Inactive' : 'Active',
    createdAt: day(400 - index * 30),
    updatedAt: day(120 - index * 20),
  }));
}

